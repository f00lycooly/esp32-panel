#!/usr/bin/env python3
"""Generate the Swelligence panel's per-spot ESPHome YAML from swell-manifest.yaml.

Expands the manifest (spots + sport slots) into:
  modules/generated/swell-text-sensors.yaml   (HA text_sensor list)
  modules/generated/swell-sensors.yaml        (HA sensor list, incl pills)
  modules/generated/swell-pages.yaml          (lvgl pages list)
  modules/generated/swell-spot-pills.yaml     (per-sport pill widgets, )
  modules/generated/swell-nav.yaml            (nav2d count + matrix row, )
  modules/generated/swell-capture-pages.yaml  (screenshot page list, )

page-swelligence.yaml !includes the sensor/page/pill files; the composition root
(waveshare-p4-86-panel.yaml) consumes swell-nav.yaml (substitutions) and
swell-capture-pages.yaml (display_capture_swell package). Templates live ONCE
here; the manifest is the single source of truth. NEVER
hand-edit the generated files. Run via `make generate` (wired into validate/compile).

Tokens in the templates: @N@ = spot index, @E@ = detail entity_id,
@SLUG@ = spot slug, @P@ = pill slot index, @SPORT@ = sport key, @LABEL@ = pill label.
"""
from __future__ import annotations
import pathlib
import sys
import yaml

REPO = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = REPO / "swell-manifest.yaml"
GEN = REPO / "modules" / "generated"

BANNER = ("# DO NOT EDIT — generated by scripts/gen_swell_panel.py from\n"
          "# swell-manifest.yaml. Edit the manifest + run `make generate`.\n")

# ── per-spot text_sensor block (@N@ spot index, @E@ entity) ──
TEXT = """  # ───────── spot @N@ ─────────
  - platform: homeassistant
    id: sw@N@_name
    entity_id: @E@
    attribute: name
    on_value:
      - lvgl.label.update: {id: sw@N@_name_lbl, text: !lambda 'return x.empty() ? "—" : x.c_str();'}
  - platform: homeassistant
    id: sw@N@_water
    entity_id: @E@
    attribute: water_type
    on_value:
      - lvgl.label.update: {id: sw@N@_water_lbl, text: !lambda 'return x.c_str();'}
  - platform: homeassistant
    id: sw@N@_headline_label
    entity_id: @E@
    attribute: headline_label
    on_value:
      - lvgl.label.update: {id: sw@N@_sport_lbl, text: !lambda 'return x.empty() ? "" : x.c_str();'}
  - platform: homeassistant
    id: sw@N@_headline_sport
    entity_id: @E@
    attribute: headline_sport
    on_value:
      - lvgl.label.update:
          id: sw@N@_sport_glyph
          text: !lambda |-
            return x=="kitesurf" ? std::string("$mdi_kitesurfing") :
                   x=="wingfoil" ? std::string("$mdi_surfing") :
                   x=="sup"      ? std::string("$mdi_rowing") :
                                   std::string("$mdi_sail_boat");
  - platform: homeassistant
    id: sw@N@_verdict
    entity_id: @E@
    attribute: headline_verdict
    on_value:
      - lvgl.label.update:
          id: sw@N@_verdict_lbl
          text: !lambda |-
            if (x.empty() || x == "unknown" || x == "unavailable") return std::string("—");
            std::string u = x; for (auto &c : u) c = toupper(c);
            return u;
      - lambda: |-
          // unknown/unavailable/empty → neutral gray500, NOT the alarm red the
          // unmatched fallback would otherwise paint.
          bool bad = x.empty() || x == "unknown" || x == "unavailable";
          lv_color_t col =
            bad           ? lv_color_hex(0x9E9E9E) :
            x=="epic"     ? lv_color_hex(0x2DD4BF) :
            x=="great"    ? lv_color_hex(0x7ACF38) :
            x=="good"     ? lv_color_hex(0x4C9FFF) :
            x=="marginal" ? lv_color_hex(0xF0A030) :
                            lv_color_hex(0xEF5350);
          lv_obj_set_style_arc_color(id(sw@N@_score_arc), col, LV_PART_INDICATOR);
          lv_obj_set_style_text_color(id(sw@N@_verdict_lbl), col, 0);
  - platform: homeassistant
    id: sw@N@_tide
    entity_id: @E@
    attribute: tide_state
    on_value:
      - lvgl.label.update: {id: sw@N@_tide_lbl, text: !lambda 'return x.empty() ? "—" : x.c_str();'}
      - lambda: |-
          lv_color_t c = x=="rising" ? lv_color_hex(0x2DD4BF)
                       : x=="falling" ? lv_color_hex(0xF0A030)
                       : lv_color_hex(0x4C9FFF);
          lv_obj_set_style_text_color(id(sw@N@_tide_lbl), c, 0);
  - platform: homeassistant
    id: sw@N@_tide_next_type
    entity_id: @E@
    attribute: tide_next_type
    on_value: [lvgl.label.update: {id: sw@N@_tide_next_lbl, text: !lambda 'return x.empty() ? "" : x.c_str();'}]
  - platform: homeassistant
    id: sw@N@_tide_next_time
    entity_id: @E@
    attribute: tide_next_time
    on_value: [lvgl.label.update: {id: sw@N@_tide_time_lbl, text: !lambda 'return x.empty() ? "" : x.c_str();'}]
  - platform: homeassistant
    id: sw@N@_tide_source
    entity_id: @E@
    attribute: tide_source
    on_value:
      - lvgl.label.update:
          id: sw@N@_tide_src
          text: !lambda |-
            std::string u = x; for (auto &ch : u) ch = toupper(ch); return u;
  - platform: homeassistant
    id: sw@N@_tide_levels
    entity_id: @E@
    attribute: tide_levels
    on_value:
      - lambda: |-
          auto *c = id(sw@N@_tide_canvas);
          const int W=232, H=38;
          std::vector<float> v; const std::string &s=x; size_t i=0;
          while (i<=s.size()){ size_t j=s.find(',',i); std::string t=s.substr(i,(j==std::string::npos?s.size():j)-i); v.push_back(t.empty()?NAN:(float)atof(t.c_str())); if(j==std::string::npos) break; i=j+1; }
          int n=v.size();
          lv_canvas_fill_bg(c, lv_color_hex(0x000000), LV_OPA_TRANSP);
          if(n<2){ return; }
          float lo=1e9f,hi=-1e9f; for(float f:v) if(!std::isnan(f)){ if(f<lo)lo=f; if(f>hi)hi=f; }
          if(!(hi>lo)) hi=lo+1.0f; float rng=hi-lo;
          // Rising-teal (matches the tide card accents) at ~2px (second row below
          // each plotted pixel) — the old 1px 0x4C9FFF read too faint.
          lv_color_t lc=lv_color_hex(0x2DD4BF); int prevy=-1;
          auto px2=[&](int X,int Y){ lv_canvas_set_px(c,X,Y,lc,LV_OPA_COVER); if(Y+1<H) lv_canvas_set_px(c,X,Y+1,lc,LV_OPA_COVER); };
          for(int px=0;px<W;px++){
            float fidx=(float)px/(W-1)*(n-1); int i0=(int)fidx; int i1=(i0+1<n)?i0+1:n-1; float fr=fidx-i0;
            float a=v[i0],b=v[i1]; if(std::isnan(a)||std::isnan(b)){ prevy=-1; continue; }
            float val=a+(b-a)*fr; int y=(int)((H-2)-((val-lo)/rng)*(H-4)); if(y<0)y=0; if(y>H-1)y=H-1;
            if(prevy<0){ px2(px,y); }
            else { int y0=prevy<y?prevy:y,y1=prevy<y?y:prevy; for(int yy=y0;yy<=y1;yy++) px2(px,yy); }
            prevy=y;
          }
          for(int yy=0;yy<H;yy+=2){ lv_canvas_set_px(c,0,yy,lv_color_hex(0xC8D2DA),LV_OPA_50); }
          lv_obj_invalidate(c);
  - platform: homeassistant
    id: sw@N@_sunset
    entity_id: @E@
    attribute: sunset
    on_value: [lvgl.label.update: {id: sw@N@_sunset_lbl, text: !lambda 'return x.empty() ? "—" : ("sunset " + x);'}]
  - platform: homeassistant
    id: sw@N@_day_progress
    entity_id: @E@
    attribute: daylight_progress
    on_value: [lvgl.arc.update: {id: sw@N@_day_arc, value: !lambda 'return (float)atof(x.c_str()) * 100.0f;'}]
  - platform: homeassistant
    id: sw@N@_day_remain_s
    entity_id: @E@
    attribute: daylight_remaining_min
    on_value:
      - lvgl.label.update:
          id: sw@N@_day_remain
          text: !lambda |-
            int m=(int)atof(x.c_str()); if(m<0)m=0; char b[16]; snprintf(b,sizeof(b),"%dh %dm", m/60, m%60); return std::string(b);
"""

# ── per-spot numeric sensor block (score/wind/gust/wind_dir) ──
# Every binding NaN-guards (unavailable entity) the same way PILL_SENSOR does:
# labels show "—", the arc/needle updates and the fmod/cardinal maths are skipped.
SENSOR = """  # ───────── spot @N@ ─────────
  - platform: homeassistant
    id: sw@N@_score
    entity_id: @E@
    on_value:
      - if:
          condition: {lambda: 'return std::isnan(x);'}
          then:
            - lvgl.label.update: {id: sw@N@_score_lbl, text: "—"}
          else:
            - lvgl.arc.update: {id: sw@N@_score_arc, value: !lambda 'return x;'}
            - lvgl.label.update: {id: sw@N@_score_lbl, text: !lambda 'char b[8]; snprintf(b, sizeof(b), "%.0f", x); return b;'}
  - platform: homeassistant
    id: sw@N@_wind
    entity_id: @E@
    attribute: wind_kn
    on_value:
      - if:
          condition: {lambda: 'return std::isnan(x);'}
          then:
            - lvgl.label.update: {id: sw@N@_wind_lbl, text: "—"}
            - lvgl.label.update: {id: sw@N@_compass_spd, text: "—"}
          else:
            - lvgl.label.update: {id: sw@N@_wind_lbl, text: !lambda 'char b[16]; snprintf(b, sizeof(b), "%.0f kn", x); return b;'}
            - lvgl.label.update: {id: sw@N@_compass_spd, text: !lambda 'char b[8]; snprintf(b, sizeof(b), "%.0f", x); return b;'}
  - platform: homeassistant
    id: sw@N@_gust
    entity_id: @E@
    attribute: gust_kn
    on_value:
      - if:
          condition: {lambda: 'return std::isnan(x);'}
          then:
            - lvgl.label.update: {id: sw@N@_gust_lbl, text: "—"}
            - lvgl.label.update: {id: sw@N@_compass_gust, text: "—"}
          else:
            - lvgl.label.update: {id: sw@N@_gust_lbl, text: !lambda 'char b[20]; snprintf(b, sizeof(b), "g %.0f", x); return b;'}
            - lvgl.label.update: {id: sw@N@_compass_gust, text: !lambda 'char b[20]; snprintf(b, sizeof(b), "gust %.0f", x); return b;'}
  - platform: homeassistant
    id: sw@N@_wind_dir
    entity_id: @E@
    attribute: wind_dir_deg
    on_value:
      - if:
          condition: {lambda: 'return std::isnan(x);'}
          then:
            - lvgl.label.update: {id: sw@N@_compass_card, text: "—"}
          else:
            - lvgl.indicator.update: {id: sw@N@_wind_needle, value: !lambda 'return fmod(x, 360.0);'}
            - lvgl.label.update:
                id: sw@N@_compass_card
                text: !lambda |-
                  static const char* C[16]={"N","NNE","NE","ENE","E","ESE","SE","SSE","S","SSW","SW","WSW","W","WNW","NW","NNW"};
                  int i=((int)((x/22.5f)+0.5f))%16; if(i<0)i+=16;
                  char b[24]; snprintf(b,sizeof(b),"kn · %s", C[i]); return std::string(b);
"""

# ── nav contribution ─────────────────────────────────
# The composition root (waveshare-p4-86-panel.yaml) owns the nav2d contract for
# the four REUSABLE functions (main/climate/timer/energy). The Swelligence
# function (F4) is manifest-driven, so its two contributions to that contract are
# emitted HERE and referenced from the device file as ${swell_npages} /
# ${swell_matrix_row} — no hand-edited nav when a spot is added/removed.
#   • swell_npages      → NPAGES[F4] (number of spot pages)
#   • swell_matrix_row  → the PAGES[F4] row of the 2D page matrix
# Included as a package so its substitutions merge into the global namespace.
NAV = """substitutions:
  # nav2d contract row for the Swelligence function — see scripts/gen_swell_panel.py.
  swell_npages: "@NPAGES@"
  swell_matrix_row: "@MATRIX@"
  # Per-spot display names (title-cased manifest slugs) for the spot-tab row in
  # swell-spot-body.yaml. Always 4 emitted (the nav2d cap); absent spots → "—".
@NAMES@"""

# ── screenshot capture-page registration ─────────────
# The diagnostic lvgl_screenshot endpoint (modules/display-capture.yaml) needs a
# {name → page} entry per swell page so `GET :8080/screenshot?page=swellN` can
# capture it. Emitted as a list fragment, !included by the display_capture_swell
# package in the composition root (concatenated onto the hand-maintained
# non-swell page list). One per spot → a new spot is screenshot-able with no
# hand-edit; the last per-spot coupling in the panel.
CAPTURE = """  - name: swell@N@
    page: swell_page@N@
"""

# ── per-spot lvgl page (@N@ spot index, @F@ nav function) ──
# Includes resolve relative to THIS file (modules/generated/), so reach the
# sibling templates in modules/ with ../.
PAGE = """  - id: swell_page@N@
    styles: page_style
    <<: !include ../nav2d-swipe.yaml
    on_load:
      - script.execute: {id: nav_arrive, f: @F@, p: @N@}
    widgets:
      - <<: !include {file: ../swell-spot-body.yaml, vars: {n: "@N@"}}
"""

# ── one sport pill widget ──────────────────────────────────────────
# Stamped per sport into modules/generated/swell-spot-pills.yaml, which the
# SPORTS cell in swell-spot-body.yaml !includes ONCE with vars {n}. So ${n} (the
# spot index) stays as an ESPHome substitution resolved at include time, while
# @SPORT@/@LABEL@ are baked here. The pill starts hidden and is revealed by its
# suitability sensor's first valid publish (PILL_SENSOR); an unconfigured sport
# yields an unavailable entity (NaN) so the pill simply never shows.
PILL_WIDGET = """  - obj:
      id: sw${n}_pill_@SPORT@
      width: 92
      height: 64
      radius: 14
      bg_color: 0x16181D
      bg_opa: COVER
      border_width: 2
      border_color: 0x33373E
      pad_all: 0
      hidden: true
      clickable: false
      widgets:
        - label:
            align: TOP_MID
            y: 8
            text: "@LABEL@"
            text_font: oswald_14
            text_color: gray500
            clickable: false
        - label:
            id: sw${n}_pill_@SPORT@_score
            align: BOTTOM_MID
            y: -7
            text: "--"
            text_font: oswald_24
            text_color: white
            clickable: false
"""

# ── per-(spot,sport) numeric suitability binding ────────────────────
# Drives the score number + reveal/hide. NaN (unavailable entity) → stays hidden,
# so the manifest's sports list is a SUPERSET: a spot lacking a sport costs nothing.
PILL_SENSOR = """  - platform: homeassistant
    id: sw@N@_suit_@SPORT@
    entity_id: sensor.swelligence_@SLUG@_@SPORT@_suitability
    on_value:
      - lambda: |-
          if (std::isnan(x)) { lv_obj_add_flag(id(sw@N@_pill_@SPORT@), LV_OBJ_FLAG_HIDDEN); return; }
          lv_obj_clear_flag(id(sw@N@_pill_@SPORT@), LV_OBJ_FLAG_HIDDEN);
          char b[8]; snprintf(b, sizeof(b), "%.0f", x); lv_label_set_text(id(sw@N@_pill_@SPORT@_score), b);
"""

# ── per-(spot,sport) verdict-colour binding ─────────────────────────
# Ring + score colour from the scorer's own band (same palette as the headline
# gauge), so pills agree with the selected-detail verdict.
PILL_VERDICT = """  - platform: homeassistant
    id: sw@N@_suit_@SPORT@_verdict
    entity_id: sensor.swelligence_@SLUG@_@SPORT@_suitability
    attribute: verdict
    on_value:
      - lambda: |-
          // unknown/unavailable/empty → neutral gray500 (matches the headline gauge).
          bool bad = x.empty() || x == "unknown" || x == "unavailable";
          lv_color_t col = bad ? lv_color_hex(0x9E9E9E)
                         : x=="epic" ? lv_color_hex(0x2DD4BF)
                         : x=="great" ? lv_color_hex(0x7ACF38)
                         : x=="good" ? lv_color_hex(0x4C9FFF)
                         : x=="marginal" ? lv_color_hex(0xF0A030)
                         : lv_color_hex(0xEF5350);
          lv_obj_set_style_border_color(id(sw@N@_pill_@SPORT@), col, 0);
          lv_obj_set_style_text_color(id(sw@N@_pill_@SPORT@_score), col, 0);
"""


def main() -> int:
    m = yaml.safe_load(MANIFEST.read_text())
    spots = m["spots"]
    sports = m.get("sports", [])
    func = str(m.get("function", 4))
    GEN.mkdir(parents=True, exist_ok=True)

    def stamp(tpl: str, n: int, e: str) -> str:
        return tpl.replace("@N@", str(n)).replace("@E@", e).replace("@F@", func)

    def stamp_sport(tpl: str, n: int, slug: str, sport: dict) -> str:
        return (tpl.replace("@N@", str(n)).replace("@SLUG@", slug)
                   .replace("@SPORT@", sport["key"]).replace("@LABEL@", sport["label"]))

    texts = "".join(stamp(TEXT, i, s["entity"]) for i, s in enumerate(spots))
    sens = "".join(stamp(SENSOR, i, s["entity"]) for i, s in enumerate(spots))
    pages = "".join(stamp(PAGE, i, s["entity"]) for i, s in enumerate(spots))

    # Per-sport pill widgets (one file, ${n} for spot resolved at include time).
    pills = "".join(PILL_WIDGET.replace("@SPORT@", sp["key"]).replace("@LABEL@", sp["label"])
                    for sp in sports)
    # Per-(spot,sport) suitability bindings — score+reveal (sensor) and band colour
    # (text_sensor on the verdict attribute). Appended to the per-spot blocks above.
    for i, s in enumerate(spots):
        for sp in sports:
            sens += stamp_sport(PILL_SENSOR, i, s["slug"], sp)
            texts += stamp_sport(PILL_VERDICT, i, s["slug"], sp)

    # nav2d contribution for the swell function — emitted so the device file
    # references ${swell_npages}/${swell_matrix_row} rather than hand-counting.
    npages = len(spots)
    matrix_row = "{ " + ", ".join(f"id(swell_page{i})->obj" for i in range(npages)) + " }"
    # Display names for the spot-tab row (37l follow-up): manifest `name` if
    # present, else the title-cased slug. Padded to the 4-slot nav2d cap.
    disp = [s.get("name") or s["slug"].replace("_", " ").title() for s in spots]
    disp += ["—"] * (4 - len(disp))
    names = "".join(f'  swell_spot_{i}_name: "{nm}"\n' for i, nm in enumerate(disp[:4]))
    nav = (NAV.replace("@NPAGES@", str(npages)).replace("@MATRIX@", matrix_row)
              .replace("@NAMES@", names))

    # diagnostic screenshot capture-page registration, one per spot.
    capture = "".join(CAPTURE.replace("@N@", str(i)) for i in range(npages))

    (GEN / "swell-text-sensors.yaml").write_text(BANNER + texts)
    (GEN / "swell-sensors.yaml").write_text(BANNER + sens)
    (GEN / "swell-pages.yaml").write_text(BANNER + pages)
    (GEN / "swell-spot-pills.yaml").write_text(BANNER + pills)
    (GEN / "swell-nav.yaml").write_text(BANNER + nav)
    (GEN / "swell-capture-pages.yaml").write_text(BANNER + capture)

    print(f"[gen_swell_panel] {npages} spot(s) × {len(sports)} sport(s) → "
          f"text-sensors/sensors/pages/pills/nav/capture generated.")
    print(f"[gen_swell_panel] nav: function {func} → nav_npages[{func}]={npages}, "
          f"matrix row emitted to swell-nav.yaml (${{swell_npages}}/${{swell_matrix_row}}).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
